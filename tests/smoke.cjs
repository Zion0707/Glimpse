const { _electron: electron } = require('@playwright/test');
const assert = require('node:assert/strict');
const path = require('node:path');
const fs = require('node:fs/promises');
const os = require('node:os');

(async () => {
  const fixtureDir = await fs.mkdtemp(path.join(os.tmpdir(), 'glimpse-test-'));
  for (const name of ['landscape.svg', 'portrait.svg']) await fs.copyFile(path.join(__dirname, 'fixtures', name), path.join(fixtureDir, name));
  const app = await electron.launch({ args: [path.join(__dirname, '..'), path.join(fixtureDir, 'landscape.svg')] });
  try {
    const page = await app.firstWindow();
    assert.equal(await page.locator('.brand, .filmstrip').count(), 0);
    await page.waitForFunction(() => document.getElementById('dimensions').textContent === '1200 × 800');
    assert.equal(await page.locator('.file-row').count(), 2);
    await page.locator('#actual').click();
    assert.equal(await page.locator('#zoom-level').textContent(), '100%');
    await page.locator('#zoom-in').click();
    assert.equal(await page.locator('#zoom-level').textContent(), '120%');
    await page.locator('#rotate').click();
    assert.match(await page.locator('#main-image').getAttribute('style'), /rotate\(90deg\)/);
    await page.locator('#flip').click();
    assert.match(await page.locator('#main-image').getAttribute('style'), /scale\(-1.2,\s*1.2\)/);
    await page.locator('#next').click();
    await page.waitForFunction(() => document.getElementById('filename').textContent === 'portrait.svg' && document.getElementById('dimensions').textContent === '600 × 900');
    await page.locator('#search').fill('landscape');
    assert.equal(await page.locator('.file-row').count(), 1);
    await page.locator('#search').fill('missing');
    assert.equal(await page.locator('.file-row').count(), 0);
    await page.locator('#search').fill('');
    const sidebar = page.locator('.sidebar');
    const initialWidth = (await sidebar.boundingBox()).width;
    const handle = await page.locator('#sidebar-resizer').boundingBox();
    await page.mouse.move(handle.x + 2, handle.y + 100);
    await page.mouse.down();
    await page.mouse.move(handle.x + 82, handle.y + 100);
    await page.mouse.up();
    assert.ok((await sidebar.boundingBox()).width > initialWidth + 60);
    assert.equal(await sidebar.evaluate(el => el.getBoundingClientRect().top), 0);
    assert.equal(await page.locator('footer').evaluate(el => getComputedStyle(el).fontSize), '11px');
    await fs.mkdir(path.join(__dirname, '../docs'), { recursive: true });
    await page.screenshot({ path: path.join(__dirname, '../docs/ui-preview.png') });
    await fs.mkdir(path.join(__dirname, '../artifacts'), { recursive: true });
    await page.screenshot({ path: path.join(__dirname, '../artifacts/viewer.png') });
    await page.setViewportSize({ width: 900, height: 620 });
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
    await page.screenshot({ path: path.join(__dirname, '../artifacts/viewer-compact.png') });
    await app.evaluate(({ shell }) => { global.realTrash = shell.trashItem; shell.trashItem = async () => { throw new Error('test failure'); }; });
    await page.locator('.file-row').first().hover();
    await page.locator('.file-delete').first().click();
    await page.waitForFunction(() => document.getElementById('toast').textContent.includes('删除失败'));
    assert.equal(await page.locator('.file-row').count(), 2);
    await app.evaluate(({ shell }) => { shell.trashItem = global.realTrash; });
    await page.locator('.file-row.selected').hover();
    await page.locator('.file-row.selected .file-delete').click();
    await page.waitForFunction(() => document.getElementById('count').textContent === '1');
    assert.equal(await fs.stat(path.join(fixtureDir, 'portrait.svg')).then(() => true, () => false), false);
    await page.waitForFunction(() => document.getElementById('filename').textContent === 'landscape.svg');
    await page.locator('.file-row').hover();
    await page.locator('.file-delete').click();
    await page.waitForFunction(() => document.getElementById('count').textContent === '0');
    assert.equal(await page.locator('#welcome').isVisible(), true);
    await fs.copyFile(path.join(__dirname, 'fixtures/portrait.svg'), path.join(fixtureDir, 'portrait.svg'));
    await page.locator('#refresh').click();
    await page.waitForFunction(() => document.getElementById('count').textContent === '1');
    assert.equal(await page.locator('.file-row .name').textContent(), 'portrait.svg');
    await page.waitForFunction(() => document.getElementById('dimensions').textContent === '600 × 900');
    await page.locator('#search').fill('portrait');
    await page.locator('#refresh').click();
    assert.equal(await page.locator('#search').inputValue(), 'portrait');
    console.log('PASS: refresh restored files, search preservation, deletion and empty state');
    console.log('PASS: real Electron image loading, directory browsing, zoom, rotate, flip, search and compact layout');
    await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].close());
    await page.locator('#close-dialog').waitFor({ state: 'visible' });
    await page.screenshot({ path: path.join(__dirname, '../artifacts/close-dialog.png'), animations: 'disabled' });
    await page.keyboard.press('Escape');
    assert.equal(await page.locator('#close-dialog').isVisible(), false);
    assert.equal(await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].isVisible()), true);
    await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].close());
    await page.locator('#close-tray').click();
    await page.waitForTimeout(150);
    assert.equal(await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].isVisible()), false);
    await app.evaluate(({ app }) => app.emit('second-instance', {}, []));
    assert.equal(await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].isVisible()), true);
    const closed = app.waitForEvent('close');
    await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].close());
    await page.locator('#close-quit').click();
    await closed;
    console.log('PASS: logo, cancel close, tray hide, second-instance restore and direct exit');
  } finally { await app.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
